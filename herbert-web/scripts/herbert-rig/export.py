"""
Flattens Unity's rigged Herbert (Assets/Scenes/Herbert.prefab) into web assets.

Every sprite's world transform is composed from the prefab's bone hierarchy
(at rest pose), then the body (torso, legs, arms, plaques, neck sprite) is
rendered into one transparent image. Head + face parts are kept separate so the
web app can blink / move the mouth; their placement is written to
lib/game/rig.generated.ts.

Run from the repo root:  python3 -I herbert-web/scripts/herbert-rig/export.py
Requires Pillow + numpy. Re-run if the Unity prefab or art changes.
"""
import json, math, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
os.chdir(os.path.join(REPO, "Assets"))
sys.path.insert(0, HERE)
from rig import *  # noqa  (parses the prefab; needs cwd == Assets)

PPU = 150  # output pixels per Unity unit
FACE = {"Head", "Eyes", "Nose", "Mouth"}
rects = {}

def load(path, fid):
    im = Image.open(path).convert("RGBA")
    if fid != "21300000":
        r = rects.setdefault(path, sheet_rects(path))
        x, y, w, h = r[fid]
        im = im.crop((int(x), int(im.height - y - h), int(x + w), int(im.height - y)))
    return im

def world_of(s):
    return world(go2t[s["go"]])

def uscale(W):
    return float(np.hypot(W[0, 0], W[1, 0]))

def place(s, im):
    """Return (resized image, matrix mapping its px -> world units)."""
    W = world_of(s)
    f = PPU * uscale(W) / 100.0
    w2, h2 = max(1, round(im.width * f)), max(1, round(im.height * f))
    im2 = im.resize((w2, h2), Image.LANCZOS)
    k = 1.0 / (100.0 * f)
    S1 = np.array([[k, 0, -w2 * k / 2], [0, -k, h2 * k / 2], [0, 0, 1]])
    return im2, W @ S1

# ---- bounds of everything (units) ----
def corners(s, im):
    W = world_of(s)
    w, h = im.width / 100, im.height / 100
    pts = [(-w / 2, -h / 2), (w / 2, -h / 2), (w / 2, h / 2), (-w / 2, h / 2)]
    return [(W @ np.array([x, y, 1]))[:2] for x, y in pts]

ims = {s["name"]: load(s["path"], s["fid"]) for s in sprites}
allpts = [p for s in sprites for p in corners(s, ims[s["name"]])]
xs, ys = [p[0] for p in allpts], [p[1] for p in allpts]
pad = 0.05
X0, X1, Y0, Y1 = min(xs) - pad, max(xs) + pad, min(ys) - pad, max(ys) + pad
cw, ch = round((X1 - X0) * PPU), round((Y1 - Y0) * PPU)
canvas = Image.new("RGBA", (cw, ch), (0, 0, 0, 0))
toCanvas = np.array([[PPU, 0, -X0 * PPU], [0, -PPU, Y1 * PPU], [0, 0, 1]])

for s in sorted(sprites, key=lambda s: (s["order"], s["doc"])):
    if s["name"] in FACE:
        continue
    im2, M = place(s, ims[s["name"]])
    inv = np.linalg.inv(toCanvas @ M)
    layer = im2.transform((cw, ch), Image.AFFINE, (*inv[0, :3], *inv[1, :3]), resample=Image.BICUBIC)
    canvas.alpha_composite(layer)

# tight crop to opaque pixels so the web box hugs the figure
bbox = canvas.getbbox()
# (head is separate, so keep the full canvas — the head sits above the body bbox)
out = os.path.join(REPO, "herbert-web", "public", "assets", "herbert")
canvas.save(os.path.join(out, "body.webp"), quality=84, method=6)

# ---- head + face placement (percent of the figure box / of the head box) ----
def box_pct(s, parent=None):
    W = world_of(s)
    im = ims[s["name"]]
    cx, cy = W[0, 2], W[1, 2]
    sc = uscale(W)
    rot = math.degrees(math.atan2(W[1, 0], W[0, 0]))
    w, h = im.width / 100 * sc, im.height / 100 * sc
    return dict(cx=cx, cy=cy, w=w, h=h, rot=rot)

by = {s["name"]: box_pct(s) for s in sprites}
FW, FH = X1 - X0, Y1 - Y0
def fig(b):
    return dict(
        left=round((b["cx"] - b["w"] / 2 - X0) / FW * 100, 3),
        top=round((Y1 - b["cy"] - b["h"] / 2) / FH * 100, 3),
        width=round(b["w"] / FW * 100, 3),
        rot=round(-b["rot"], 2),  # CSS rotates clockwise
    )
head = by["Head"]
r = math.radians(-head["rot"])
def inhead(b):
    dx, dy = b["cx"] - head["cx"], b["cy"] - head["cy"]
    lx, ly = dx * math.cos(r) - dy * math.sin(r), dx * math.sin(r) + dy * math.cos(r)
    return dict(
        left=round((lx - b["w"] / 2) / head["w"] * 100 + 50, 3),
        top=round(50 - (ly + b["h"] / 2) / head["h"] * 100, 3),
        width=round(b["w"] / head["w"] * 100, 3),
        rot=round(-(b["rot"] - head["rot"]), 2),
    )

def figure_pt(wx, wy):  # world point -> percent of figure box
    return [round((wx - X0) / FW * 100, 2), round((Y1 - wy) / FH * 100, 2)]

rig = dict(
    aspect=[cw, ch],
    head=fig(head),
    headAspect=[ims["Head"].width, ims["Head"].height],
    eyes=inhead(by["Eyes"]),
    nose=inhead(by["Nose"]),
    mouth=inhead(by["Mouth"]),
    bounds=dict(x0=X0, x1=X1, y0=Y0, y1=Y1),
)
rig["_hint"] = "Use figure_pt(world x,y) to place hotspots; see export.py"
ts = "// GENERATED by scripts/herbert-rig/export.py — do not edit by hand.\nexport const RIG = " + json.dumps(
    {k: v for k, v in rig.items() if k != "_hint"}, indent=2) + " as const;\n"
open(os.path.join(REPO, "herbert-web", "lib", "game", "rig.generated.ts"), "w").write(ts)
print("canvas", cw, ch, "bounds", [round(v, 2) for v in (X0, X1, Y0, Y1)])
print(json.dumps(rig, indent=1))
# key world points for hotspots (units) printed for reference
for n in ("Right_arm", "Left_arm", "Herbert_torso", "NeckSocket", "Head"):
    print(n, figure_pt(by[n]["cx"], by[n]["cy"]))
